//! Colors for the window and the text. One Dark and One Light.

pub type Rgb = [u8; 3];

#[derive(Clone, Copy, PartialEq)]
pub struct Theme {
    pub dark: bool,
    pub name: &'static str,
    /// Terminal background.
    pub bg: Rgb,
    /// Title bar background.
    pub bar: Rgb,
    /// Popup background.
    pub panel: Rgb,
    /// Selected row in a popup, and the active tab.
    pub panel_hi: Rgb,
    pub border: Rgb,
    pub fg: Rgb,
    /// Secondary text.
    pub dim: Rgb,
    pub accent: Rgb,
    pub red: Rgb,
    pub yellow: Rgb,
    pub green: Rgb,
    pub cyan: Rgb,
    pub selection: Rgb,
    /// Background of a find match.
    pub find: Rgb,
    /// The 16 ANSI colors.
    pub ansi: [Rgb; 16],
}

